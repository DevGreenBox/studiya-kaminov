/**
 * Русская типографика: убирает висячие предлоги и разрывы в неделимых парах.
 *
 * Функция работает с обычными строками, которые React выводит как текст,
 * поэтому html-сущности не нужны — подставляется настоящий символ U+00A0.
 */

const NBSP = ' ';

/**
 * Служебные слова, которые нельзя оставлять в конце строки.
 * Односложные предлоги и частицы (1–2 буквы) обрабатываются отдельным
 * правилом, здесь — те, что длиннее.
 */
const SHORT_WORDS = [
  // предлоги
  'без',
  'для',
  'над',
  'под',
  'при',
  'про',
  'изо',
  'обо',
  'ото',
  'подо',
  'передо',
  'через',
  'между',
  'после',
  'перед',
  'около',
  'кроме',
  // союзы и частицы
  'как',
  'что',
  'или',
  'либо',
  'если',
  'чтобы',
  'также',
  'тоже',
  'ведь',
  'лишь',
  'даже',
  'пока',
  'хотя',
  'уже',
  'ещё',
  // местоимения, которые тоже некрасиво висят
  'она',
  'оно',
  'они',
  'его',
  'её',
  'их',
  'это',
  'этот',
  'эта',
  'эти',
  'все',
  'всё',
];

/** Единицы измерения, которые остаются рядом с числом. */
const UNITS = [
  '₽',
  'руб',
  'м²',
  'мм',
  'см',
  'м',
  'кг',
  'г',
  'шт',
  'Вт',
  'кВт',
  'В',
  'мин',
  'дн',
  '%',
  '″',
];

const escape = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/*
 * Границу слова проверяем ретроспективной проверкой, а не захватом символа:
 * при захвате разделитель «съедался» и два предлога подряд («или при»)
 * обрабатывались только через один.
 *
 * Порядок слов в списке не важен: если короткая альтернатива вроде «это»
 * перехватит начало слова «этот», проверка пробела следом не пройдёт и движок
 * вернётся к более длинному варианту.
 */
const SHORT_1_2 = /(?<=^|[\s(«"„])([a-zа-яё]{1,2})[ \t]+/gi;
const SHORT_LONG = new RegExp(`(?<=^|[\\s(«"„])(${SHORT_WORDS.join('|')})[ \\t]+`, 'gi');
const NUMBER_UNIT = new RegExp(`(\\d)\\s+(${UNITS.map(escape).join('|')})(?![a-zа-яё])`, 'gi');
const NUMBER_SIGN = /№\s+(?=\d)/g;
const BEFORE_DASH = /\s+(—|–)/g;
const INITIALS = /(\d)\s+(×)\s+(\d)/g;

/**
 * Расставляет неразрывные пробелы.
 *
 * Что склеивается:
 *  * короткие слова (1–3 буквы) со следующим словом — «в​ гостиной», «до 25 м²»;
 *  * число с единицей измерения — «44 900 ₽», «952 мм»;
 *  * тире с предыдущим словом, чтобы оно не начинало строку;
 *  * номер со знаком «№».
 *
 * Разряды в числах («44 900») исходно заданы узким неразрывным пробелом
 * из Intl, поэтому здесь не трогаются.
 */
export function typo(text: string): string {
  return text
    .replace(SHORT_LONG, (_m, word: string) => `${word}${NBSP}`)
    .replace(SHORT_1_2, (_m, word: string) => `${word}${NBSP}`)
    .replace(NUMBER_UNIT, (_m, digit: string, unit: string) => `${digit}${NBSP}${unit}`)
    .replace(INITIALS, (_m, a: string, sign: string, b: string) => `${a}${NBSP}${sign}${NBSP}${b}`)
    .replace(NUMBER_SIGN, `№${NBSP}`)
    .replace(BEFORE_DASH, (_m, dash: string) => `${NBSP}${dash}`);
}

/** Применяет типографику к абзацам, разделённым пустой строкой. */
export const typoParagraphs = (text: string) => text.split('\n\n').map(typo);
